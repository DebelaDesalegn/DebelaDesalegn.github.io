"use client";

import { useState } from "react";
import { AnimatePresence, motion, useReducedMotion } from "framer-motion";
import { asset } from "@/lib/site";

/**
 * DiffuSAGE token-to-region attribution for the prompt
 * "an astronaut riding a horse on Mars" (Stable Diffusion v1.5).
 * Heatmaps and token importance shading are taken from the DiffuSAGE manuscript (Figures 3 and 9).
 */
type Token = { text: string; heatmap?: string; weight: number };

const TOKENS: Token[] = [
  { text: "an", weight: 0.05 },
  { text: "astronaut", heatmap: "astronaut", weight: 0.95 },
  { text: "riding", weight: 0.6 },
  { text: "a", weight: 0.3 },
  { text: "horse", heatmap: "horse", weight: 0.6 },
  { text: "on", weight: 0.1 },
  { text: "Mars", heatmap: "mars", weight: 1 },
];

const DESCRIPTIONS: Record<string, string> = {
  astronaut: "Attribution concentrates on the rider: the helmet, suit and torso.",
  horse: "Attribution shifts to the animal's body and legs, while the rider fades.",
  Mars: "Attribution covers the terrain and sky, the scene's environmental context.",
};

export function TokenAttributionExplorer({ compact = false }: { compact?: boolean }) {
  const [active, setActive] = useState<Token>(TOKENS[1]);
  const reduce = useReducedMotion();

  return (
    <figure className="not-prose my-2">
      <div className="flex flex-wrap items-center gap-1.5" role="group" aria-label="Prompt tokens">
        {TOKENS.map((t) => {
          const selectable = Boolean(t.heatmap);
          const selected = active.text === t.text;
          const bg = `color-mix(in srgb, var(--accent) ${Math.round(t.weight * 85)}%, var(--paper))`;
          return (
            <button
              key={t.text}
              type="button"
              disabled={!selectable}
              aria-pressed={selectable ? selected : undefined}
              onClick={() => selectable && setActive(t)}
              className={`rounded-sm px-2.5 py-1 font-serif text-[1.02rem] transition-shadow ${
                t.weight > 0.55 ? "text-white" : "text-ink"
              } ${selectable ? "cursor-pointer hover:ring-2 hover:ring-accent/40" : "cursor-default"} ${
                selected ? "ring-2 ring-ink ring-offset-2 ring-offset-paper" : ""
              }`}
              style={{ background: bg }}
              title={selectable ? `Show where "${t.text}" acts in the image` : "Heatmap not shown for this token"}
            >
              {t.text}
            </button>
          );
        })}
      </div>
      <p className="mt-2 text-[0.82rem] text-ink-3">
        Shading shows each token&apos;s overall importance. Select <span className="text-ink-2">astronaut</span>,{" "}
        <span className="text-ink-2">horse</span> or <span className="text-ink-2">Mars</span> to see where it acts in the image.
      </p>

      <div className={`mt-4 grid grid-cols-2 gap-3 ${compact ? "max-w-[36rem]" : "max-w-[44rem]"}`}>
        <div>
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={asset("/figures/ds-generated.jpg")}
            alt="Image generated by Stable Diffusion v1.5 for the prompt: an astronaut riding a horse on Mars"
            width={480}
            height={480}
            className="aspect-square w-full border border-rule object-cover"
          />
          <p className="mt-1.5 text-[0.82rem] text-ink-3">Generated image</p>
        </div>
        <div>
          <div className="relative aspect-square w-full overflow-hidden border border-rule bg-shelf">
            <AnimatePresence initial={false}>
              <motion.img
                key={active.heatmap}
                src={asset(`/figures/ds-${active.heatmap}.jpg`)}
                alt={`DiffuSAGE attribution heatmap for the token "${active.text}"`}
                width={480}
                height={480}
                className="absolute inset-0 h-full w-full object-cover"
                initial={reduce ? false : { opacity: 0 }}
                animate={{ opacity: 1 }}
                exit={reduce ? { opacity: 0 } : { opacity: 0 }}
                transition={{ duration: 0.35 }}
              />
            </AnimatePresence>
          </div>
          <p className="mt-1.5 text-[0.82rem] text-ink-3" aria-live="polite">
            Attribution for <span className="font-medium text-ink">{active.text}</span>
          </p>
        </div>
      </div>
      <figcaption className="mt-3 max-w-[44rem] text-[0.9rem] leading-snug text-ink-2">
        {DESCRIPTIONS[active.text]} DiffuSAGE token-to-region attribution on Stable Diffusion v1.5 for the prompt
        &ldquo;an astronaut riding a horse on Mars&rdquo;; brighter regions are more strongly attributed to the token.
      </figcaption>
    </figure>
  );
}
